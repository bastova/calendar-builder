export const printerById = id => PRINTERS.find(printer=>printer.id===id) || PRINTERS[0];
const fits=(width,height,size)=>(width<=size[0]+1e-6&&height<=size[1]+1e-6)||(height<=size[0]+1e-6&&width<=size[1]+1e-6);
/** A nominal sheet fit is not a guarantee of printable area or media support. */
export function assessPrinterMedia(printer,geometry){
  const {width,height}=geometry;
  if(printer.rollWidth) return {status:Math.min(width,height)<=printer.rollWidth?'width-only':'outside-width',printable:null};
  if(!printer.sheet)return {status:'unknown',printable:null};
  return {status:(printer.sheets||[printer.sheet]).some(size=>fits(width,height,size))?'nominal-fit':'outside-reference',printable:printer.imageArea?fits(width,height,printer.imageArea):null};
}
